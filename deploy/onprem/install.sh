#!/usr/bin/env bash
# One-time setup for a Mosaic OMS on-prem box (Ubuntu/Debian, amd64 or arm64).
#
#   curl -fsSL https://raw.githubusercontent.com/milesressler/mosaic-oms/main/deploy/onprem/install.sh | sudo bash
#
# Safe to re-run: it keeps existing passwords, keys and data.
# Answers can be preset with env vars (MOSAIC_HOSTNAME, INGRESS, ACME_EMAIL,
# INSTALL_TAILSCALE=y|n) for a non-interactive install.

set -Eeuo pipefail

REPO_URL="${MOSAIC_REPO_URL:-https://github.com/milesressler/mosaic-oms.git}"
BRANCH="${MOSAIC_BRANCH:-main}"
IMAGE_REF_DEFAULT="${MOSAIC_IMAGE_REF:-ghcr.io/milesressler/mosaic-oms:main}"
SRC=/opt/mosaic/src
ETC=/etc/mosaic
DATA=/var/lib/mosaic
SOPS_VERSION=3.9.4

say()  { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
die()  { printf '\033[31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

# Prompts read from the terminal even when the script is piped into bash.
ask() {  # var prompt default
  local var="$1" prompt="$2" def="${3:-}" ans
  if [[ -n "${!var:-}" ]]; then return; fi
  if [[ -r /dev/tty ]]; then
    read -r -p "$prompt${def:+ [$def]}: " ans </dev/tty || true
  fi
  printf -v "$var" '%s' "${ans:-$def}"
}

gen_pw() { openssl rand -base64 33 | tr -dc 'A-Za-z0-9' | head -c 32; }

[[ $EUID -eq 0 ]] || die "run with sudo"
command -v apt-get >/dev/null || die "this installer supports Ubuntu/Debian (apt). Other distros: install docker, git, sops, age by hand and re-run."

case "$(uname -m)" in
  x86_64)  ARCH=amd64 ;;
  aarch64) ARCH=arm64 ;;
  *) die "unsupported CPU $(uname -m)" ;;
esac

say "Installing packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq git curl openssl ca-certificates age nano >/dev/null

if ! command -v docker >/dev/null || ! docker compose version >/dev/null 2>&1; then
  say "Installing Docker"
  curl -fsSL https://get.docker.com | sh
fi
systemctl enable --now docker

if ! sops --version 2>/dev/null | grep -q "$SOPS_VERSION"; then
  say "Installing sops $SOPS_VERSION"
  tmp="$(mktemp -d)"
  base="https://github.com/getsops/sops/releases/download/v$SOPS_VERSION"
  curl -fsSL -o "$tmp/sops-v$SOPS_VERSION.linux.$ARCH" "$base/sops-v$SOPS_VERSION.linux.$ARCH"
  curl -fsSL -o "$tmp/checksums.txt" "$base/sops-v$SOPS_VERSION.checksums.txt"
  (cd "$tmp" && grep " sops-v$SOPS_VERSION.linux.$ARCH\$" checksums.txt | sha256sum -c -) || die "sops checksum mismatch"
  install -m 755 "$tmp/sops-v$SOPS_VERSION.linux.$ARCH" /usr/local/bin/sops
  rm -rf "$tmp"
fi

say "Fetching Mosaic OMS deploy files"
if [[ -d "$SRC/.git" ]]; then
  git -C "$SRC" fetch -q origin "$BRANCH" && git -C "$SRC" reset -q --hard FETCH_HEAD
else
  mkdir -p "$(dirname "$SRC")"
  git clone -q --branch "$BRANCH" "$REPO_URL" "$SRC"
fi

mkdir -p "$ETC" "$DATA"/{backups,state,run}
chmod 700 "$ETC" "$DATA/backups" "$DATA/state" "$DATA/run"

if [[ ! -f "$ETC/box.env" ]]; then
  say "Site settings"
  echo "The public web address people will use, e.g. portal.mosaicstreetministry.com"
  ask MOSAIC_HOSTNAME "Hostname"
  [[ -n "$MOSAIC_HOSTNAME" ]] || die "hostname is required"
  echo
  echo "How does the internet reach this box?"
  echo "  caddy       - ports 80 and 443 are forwarded to this box; HTTPS cert is automatic"
  echo "  cloudflared - Cloudflare Tunnel; no port forwarding (needs TUNNEL_TOKEN in secrets)"
  ask INGRESS "caddy or cloudflared" "caddy"
  [[ "$INGRESS" == caddy || "$INGRESS" == cloudflared ]] || die "INGRESS must be caddy or cloudflared"
  if [[ "$INGRESS" == caddy ]]; then
    ask ACME_EMAIL "Email for Let's Encrypt certificate notices"
    [[ -n "$ACME_EMAIL" ]] || die "email is required for caddy"
  fi

  umask 077
  cat >"$ETC/box.env" <<EOF
# Box-local settings. Generated by install.sh on $(date -u +%F).
# The passwords below never leave this machine. Changing DB passwords here
# does NOT change them in MySQL - leave them alone unless you know how.

MOSAIC_HOSTNAME=$MOSAIC_HOSTNAME
INGRESS=$INGRESS
ACME_EMAIL=${ACME_EMAIL:-}

IMAGE_REF=$IMAGE_REF_DEFAULT
BRANCH=$BRANCH
# Only needed if the container image is private (GitHub PAT with read:packages)
REGISTRY_USER=
REGISTRY_TOKEN=

MYSQL_ROOT_PASSWORD=$(gen_pw)
DB_PASSWORD=$(gen_pw)
DB_READONLY_PASSWORD=$(gen_pw)

BACKUP_KEEP_DAYS=30
EOF
  umask 022
else
  say "Keeping existing $ETC/box.env"
fi

if [[ ! -f "$ETC/age.key" ]]; then
  age-keygen -o "$ETC/age.key" 2>/dev/null
fi
chmod 600 "$ETC/age.key" "$ETC/box.env"
AGE_PUB="$(age-keygen -y "$ETC/age.key")"

ln -sf "$SRC/deploy/onprem/bin/mosaic" /usr/local/bin/mosaic
chmod +x "$SRC/deploy/onprem/bin/mosaic"

ask INSTALL_TAILSCALE "Install Tailscale so the developer can help remotely? (y/n)" "y"
if [[ "$INSTALL_TAILSCALE" =~ ^[Yy] ]] && ! command -v tailscale >/dev/null; then
  say "Installing Tailscale"
  curl -fsSL https://tailscale.com/install.sh | sh
  echo "Run 'sudo tailscale up --ssh' and log in to finish connecting this box."
fi

say "First deploy"
if mosaic deploy; then
  DEPLOY_OK=1
else
  DEPLOY_OK=0
fi

cat <<EOF

============================================================================
 Mosaic OMS box is installed. It checks for updates every 5 minutes.

 This box's public key (send it to the developer - it is NOT a secret):

     $AGE_PUB

 Useful commands:   mosaic status   mosaic logs app   mosaic help
============================================================================
EOF
if [[ $DEPLOY_OK -eq 0 ]]; then
  cat <<EOF
 The app isn't running yet. That's expected until the developer adds the key
 above to deploy/onprem/config/.sops.yaml and pushes secrets.env. The box will
 pick it up automatically within 5 minutes.
EOF
fi
